import { readFileSync, writeFileSync } from 'node:fs'
import { resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import openapiTS, { astToString } from 'openapi-typescript'

const scriptDirectory = fileURLToPath(new URL('.', import.meta.url))
const appDirectory = resolve(scriptDirectory, '..')
const snapshotPath = resolve(appDirectory, '../pms-api/src/test/resources/openapi-contract.json')
const generatedPath = resolve(appDirectory, 'src/api/generated.ts')
const liveUrl = process.env.PMS_OPENAPI_URL || 'http://localhost:8088/v3/api-docs'
const sync = process.argv.includes('--sync')
const checkLive = process.argv.includes('--check-live')

function canonical(value) {
  if (Array.isArray(value)) return value.map(canonical)
  if (value && typeof value === 'object') {
    return Object.fromEntries(Object.keys(value).sort().map((key) => [key, canonical(value[key])]))
  }
  return value
}

function equivalent(left, right) {
  return JSON.stringify(canonical(left)) === JSON.stringify(canonical(right))
}

function normalizeContract(contract) {
  const normalized = structuredClone(contract)
  delete normalized.servers
  return normalized
}

async function fetchLiveContract() {
  const response = await fetch(liveUrl, { headers: { Accept: 'application/json' }, signal: AbortSignal.timeout(15_000) })
  if (!response.ok) throw new Error(`OpenAPI endpoint returned HTTP ${response.status}: ${liveUrl}`)
  const contract = await response.json()
  if (!String(contract.openapi || '').startsWith('3.')) throw new Error('OpenAPI endpoint did not return an OpenAPI 3 document.')
  return normalizeContract(contract)
}

let snapshot
if (sync || checkLive) {
  const live = await fetchLiveContract()
  if (sync) {
    writeFileSync(snapshotPath, `${JSON.stringify(live, null, 2)}\n`, 'utf8')
    snapshot = live
  } else {
    snapshot = normalizeContract(JSON.parse(readFileSync(snapshotPath, 'utf8')))
    if (!equivalent(live, snapshot)) {
      console.error('Live backend OpenAPI differs from the committed contract snapshot. Run: npm run api:generate')
      process.exit(1)
    }
  }
} else {
  snapshot = normalizeContract(JSON.parse(readFileSync(snapshotPath, 'utf8')))
}

const generated = `/**
 * This file was auto-generated by openapi-typescript.
 * Do not make direct changes to the file.
 */

${astToString(await openapiTS(snapshot))}`
if (sync) {
  writeFileSync(generatedPath, generated, 'utf8')
  console.log(`Synchronized OpenAPI snapshot and TypeScript types from ${liveUrl}`)
} else {
  const committed = readFileSync(generatedPath, 'utf8')
  if (committed !== generated) {
    console.error('Generated TypeScript API types differ from the committed contract. Run: npm run api:generate')
    process.exit(1)
  }
  console.log(`OpenAPI contract types are current${checkLive ? ' and live backend matches snapshot' : ''}.`)
}
